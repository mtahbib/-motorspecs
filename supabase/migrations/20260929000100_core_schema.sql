-- =============================================================================
-- MotorSpecs core schema
--
-- Conventions
--   * Every table lives in `public` and has Row Level Security enabled
--     (policies are in 20260929000400_rls_policies.sql).
--   * Status-like columns are text + CHECK constraints so values can be added
--     later without enum migrations.
--   * Child rows that belong to a customer carry a denormalised `customer_id`
--     that is set by trigger from the parent row, never trusted from the client.
--   * `is_demo` marks seed/demo rows so they can be purged before go-live
--     (see supabase/scripts/purge_demo_data.sql).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Reference sequences for human-readable numbers
-- -----------------------------------------------------------------------------
create sequence if not exists public.customer_code_seq start 10001;
create sequence if not exists public.vehicle_ref_seq start 24001;
create sequence if not exists public.inquiry_ref_seq start 5001;
create sequence if not exists public.sale_no_seq start 1001;

-- -----------------------------------------------------------------------------
-- Profiles: one row per auth user (staff and customers)
-- -----------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'customer' check (role in ('admin', 'sales', 'customer')),
  display_name text check (char_length(display_name) <= 120),
  email text,
  phone text check (char_length(phone) <= 40),
  locale text not null default 'en' check (locale in ('en', 'ja', 'ar')),
  -- The business owner. Cannot be demoted or deactivated from the app.
  is_owner boolean not null default false,
  is_active boolean not null default true,
  -- When true, staff privileges are only granted to sessions that completed
  -- authenticator-app MFA (JWT aal = 'aal2'). See public.is_staff().
  mfa_required boolean not null default false,
  is_demo boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index profiles_email_key on public.profiles (lower(email));

-- -----------------------------------------------------------------------------
-- Lookups
-- -----------------------------------------------------------------------------
create table public.makes (
  id smallint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  sort_order smallint not null default 100
);

create table public.models (
  id integer generated by default as identity primary key,
  make_id smallint not null references public.makes (id) on delete restrict,
  name text not null,
  slug text not null check (slug ~ '^[a-z0-9-]+$'),
  unique (make_id, slug)
);

create table public.body_types (
  code text primary key check (code ~ '^[a-z_]+$'),
  sort_order smallint not null default 100
);

create table public.locations (
  id smallint generated by default as identity primary key,
  name text not null unique,
  country_code char(2) not null default 'JP',
  port text
);

create table public.features (
  code text primary key check (code ~ '^[a-z0-9_]+$'),
  category text not null check (category in ('comfort', 'safety', 'exterior', 'interior', 'audio', 'utility')),
  sort_order smallint not null default 100
);

-- -----------------------------------------------------------------------------
-- Customers: the master customer database.
-- A row may exist before the person signs up (created by staff). It is linked to
-- a login (auth_user_id) only through a verified invite code.
-- -----------------------------------------------------------------------------
create table public.customers (
  id uuid primary key default gen_random_uuid(),
  customer_code text not null unique
    default ('MSC-' || nextval('public.customer_code_seq')::text),
  auth_user_id uuid unique references auth.users (id) on delete set null,
  status text not null default 'active' check (status in ('lead', 'active', 'inactive', 'merged')),
  merged_into uuid references public.customers (id),

  -- Customer-editable profile fields
  full_name text not null check (char_length(full_name) between 1 and 160),
  company_name text check (char_length(company_name) <= 160),
  phone text check (char_length(phone) <= 40),
  whatsapp text check (char_length(whatsapp) <= 40),
  country_code char(2),
  city text check (char_length(city) <= 120),
  address_line text check (char_length(address_line) <= 300),
  postal_code text check (char_length(postal_code) <= 20),
  destination_port text check (char_length(destination_port) <= 120),
  preferred_language text not null default 'en' check (preferred_language in ('en', 'ja', 'ar')),
  preferred_contact text not null default 'email' check (preferred_contact in ('email', 'phone', 'whatsapp')),

  -- Admin-controlled fields (read-only to customers, enforced by trigger)
  email text check (char_length(email) <= 254),
  verification_status text not null default 'unverified'
    check (verification_status in ('unverified', 'pending', 'verified', 'rejected')),
  verified_name text,
  verified_company text,
  verified_at timestamptz,
  verified_by uuid references public.profiles (id),
  assigned_staff_id uuid references public.profiles (id),
  source text not null default 'website' check (source in ('website', 'staff', 'import', 'referral')),
  tags text[] not null default '{}',

  is_demo boolean not null default false,
  created_by uuid references public.profiles (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index customers_assigned_idx on public.customers (assigned_staff_id);
create index customers_email_idx on public.customers (lower(email));
create index customers_phone_idx on public.customers (phone);

-- Full history of who owned the customer relationship.
create table public.customer_assignments (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers (id) on delete cascade,
  from_staff_id uuid references public.profiles (id),
  to_staff_id uuid references public.profiles (id),
  assigned_by uuid references public.profiles (id),
  reason text check (char_length(reason) <= 500),
  created_at timestamptz not null default now()
);

create index customer_assignments_customer_idx on public.customer_assignments (customer_id, created_at desc);

-- One-time codes that let a registered user claim a staff-created record.
-- Only the SHA-256 hash of the code is stored.
create table public.customer_invites (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers (id) on delete cascade,
  code_hash text not null unique,
  code_hint text not null,
  expires_at timestamptz not null default now() + interval '14 days',
  used_at timestamptz,
  used_by uuid references auth.users (id),
  revoked_at timestamptz,
  created_by uuid references public.profiles (id),
  created_at timestamptz not null default now()
);

-- -----------------------------------------------------------------------------
-- Vehicles
-- -----------------------------------------------------------------------------
create table public.vehicles (
  id uuid primary key default gen_random_uuid(),

  -- Identity
  ref_no text not null unique default ('MS' || nextval('public.vehicle_ref_seq')::text)
    check (ref_no ~ '^[A-Za-z0-9-]{2,30}$'),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  chassis_no text check (char_length(chassis_no) <= 40),
  model_code text check (char_length(model_code) <= 40),
  engine_code text check (char_length(engine_code) <= 40),
  condition_grade text check (char_length(condition_grade) <= 10),
  auction_sheet_ref text check (char_length(auction_sheet_ref) <= 80),

  -- Classification
  make_id smallint references public.makes (id),
  model_id integer references public.models (id),
  body_type text references public.body_types (code),
  location_id smallint references public.locations (id),
  reg_year smallint check (reg_year between 1950 and 2100),
  reg_month smallint check (reg_month between 1 and 12),
  manufacture_year smallint check (manufacture_year between 1950 and 2100),
  grade text check (char_length(grade) <= 120),

  -- Specifications
  mileage_km integer check (mileage_km >= 0),
  operating_hours integer check (operating_hours >= 0),
  engine_cc integer check (engine_cc between 0 and 30000),
  transmission text check (transmission in ('AT', 'MT', 'CVT', 'AMT', 'other')),
  fuel text check (fuel in ('petrol', 'diesel', 'hybrid', 'plugin_hybrid', 'electric', 'lpg', 'other')),
  drive text check (drive in ('2WD', '4WD', 'AWD')),
  steering text check (steering in ('RHD', 'LHD')),
  exterior_color text check (char_length(exterior_color) <= 60),
  interior_color text check (char_length(interior_color) <= 60),
  doors smallint check (doors between 0 and 8),
  seats smallint check (seats between 0 and 60),
  has_360_view boolean not null default false,

  -- Customs / shipping information
  length_mm integer check (length_mm between 0 and 30000),
  width_mm integer check (width_mm between 0 and 5000),
  height_mm integer check (height_mm between 0 and 6000),
  m3 numeric(7, 2) check (m3 >= 0),
  weight_kg integer check (weight_kg >= 0),
  gross_weight_kg integer check (gross_weight_kg >= 0),
  max_load_kg integer check (max_load_kg >= 0),
  tyre_front text check (char_length(tyre_front) <= 40),
  tyre_rear text check (char_length(tyre_rear) <= 40),

  -- Public pricing. `ask` = "Ask for price": the amount is never exposed.
  price_visibility text not null default 'ask' check (price_visibility in ('public', 'ask')),
  fob_price_usd numeric(12, 2) check (fob_price_usd > 0),
  previous_price_usd numeric(12, 2) check (previous_price_usd > 0),

  -- Publishing
  status text not null default 'draft' check (status in ('draft', 'published', 'reserved', 'sold', 'archived')),
  is_featured boolean not null default false,
  published_at timestamptz,

  is_demo boolean not null default false,
  created_by uuid references public.profiles (id),
  updated_by uuid references public.profiles (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint vehicles_public_price_requires_amount
    check (price_visibility = 'ask' or fob_price_usd is not null)
);

create index vehicles_status_idx on public.vehicles (status, published_at desc);
create index vehicles_make_model_idx on public.vehicles (make_id, model_id);

-- Private information that must never reach the public site or customers.
