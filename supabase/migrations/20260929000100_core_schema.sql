  new_price_usd numeric(12, 2),
  old_visibility text,
  new_visibility text,
  changed_by uuid references public.profiles (id),
  changed_at timestamptz not null default now()
);

create table public.vehicle_status_history (
  id uuid primary key default gen_random_uuid(),
  vehicle_id uuid not null references public.vehicles (id) on delete cascade,
  from_status text,
  to_status text not null,
  changed_by uuid references public.profiles (id),
  changed_at timestamptz not null default now()
);

create table public.favorites (
  customer_id uuid not null references public.customers (id) on delete cascade,
  vehicle_id uuid not null references public.vehicles (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (customer_id, vehicle_id)
);

-- -----------------------------------------------------------------------------
-- Deals: inquiries -> messages / notes / offers -> reservations -> sales
-- -----------------------------------------------------------------------------
create table public.inquiries (
  id uuid primary key default gen_random_uuid(),
  ref_no text not null unique default ('INQ-' || nextval('public.inquiry_ref_seq')::text),
  customer_id uuid not null references public.customers (id),
  vehicle_id uuid references public.vehicles (id),
  kind text not null default 'inquiry' check (kind in ('inquiry', 'offer')),
  subject text not null check (char_length(subject) between 1 and 200),
  status text not null default 'new'
    check (status in ('new', 'open', 'quoted', 'negotiating', 'reserved', 'won', 'lost', 'closed')),
  destination_port text check (char_length(destination_port) <= 120),
  follow_up_at timestamptz,
  last_message_at timestamptz not null default now(),
  closed_reason text check (char_length(closed_reason) <= 500),
  is_demo boolean not null default false,
  created_by uuid references public.profiles (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index inquiries_customer_idx on public.inquiries (customer_id, last_message_at desc);
create index inquiries_status_idx on public.inquiries (status, last_message_at desc);

create table public.messages (
  id uuid primary key default gen_random_uuid(),
  inquiry_id uuid not null references public.inquiries (id) on delete cascade,
  customer_id uuid not null references public.customers (id),
  sender_id uuid references public.profiles (id),
  sender_role text not null check (sender_role in ('admin', 'sales', 'customer', 'system')),
  body text not null check (char_length(body) between 1 and 5000),
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index messages_inquiry_idx on public.messages (inquiry_id, created_at);

-- Staff-only notes. Kept in a separate table so they can never leak through a
-- customer's message policy.
create table public.internal_notes (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers (id),
  inquiry_id uuid references public.inquiries (id) on delete cascade,
  author_id uuid references public.profiles (id),
  body text not null check (char_length(body) between 1 and 5000),
  created_at timestamptz not null default now()
);

create index internal_notes_customer_idx on public.internal_notes (customer_id, created_at desc);

create table public.offers (
  id uuid primary key default gen_random_uuid(),
  inquiry_id uuid not null references public.inquiries (id) on delete cascade,
  customer_id uuid not null references public.customers (id),
  vehicle_id uuid references public.vehicles (id),
  kind text not null check (kind in ('customer_offer', 'counter_offer', 'quotation')),
  amount_usd numeric(12, 2) not null check (amount_usd > 0 and amount_usd < 10000000),
  incoterm text not null default 'FOB' check (incoterm in ('FOB', 'CFR', 'CIF')),
  freight_usd numeric(12, 2) check (freight_usd >= 0),
  insurance_usd numeric(12, 2) check (insurance_usd >= 0),
  inspection_usd numeric(12, 2) check (inspection_usd >= 0),
  destination_port text check (char_length(destination_port) <= 120),
  valid_until date,
  message text check (char_length(message) <= 2000),
  status text not null default 'pending'
    check (status in ('pending', 'accepted', 'declined', 'withdrawn', 'expired', 'superseded')),
  responded_at timestamptz,
  responded_by uuid references public.profiles (id),
  created_by uuid references public.profiles (id),
  created_at timestamptz not null default now()
);

create index offers_inquiry_idx on public.offers (inquiry_id, created_at);

create table public.reservations (
  id uuid primary key default gen_random_uuid(),
  vehicle_id uuid not null references public.vehicles (id),
  customer_id uuid not null references public.customers (id),
  inquiry_id uuid references public.inquiries (id),
  offer_id uuid references public.offers (id),
  status text not null default 'active' check (status in ('active', 'released', 'expired', 'converted')),
  agreed_price_usd numeric(12, 2) check (agreed_price_usd > 0),
  reserved_until timestamptz not null default now() + interval '5 days',
  notes text check (char_length(notes) <= 2000),
  released_at timestamptz,
  release_reason text check (char_length(release_reason) <= 500),
  is_demo boolean not null default false,
  reserved_by uuid references public.profiles (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- A vehicle can only have one active reservation at a time.
create unique index reservations_one_active_per_vehicle
  on public.reservations (vehicle_id) where status = 'active';
create index reservations_customer_idx on public.reservations (customer_id);

create table public.sales (
  id uuid primary key default gen_random_uuid(),
  sale_no text not null unique
    default ('SO-' || to_char(now(), 'YYYY') || '-' || nextval('public.sale_no_seq')::text),
  vehicle_id uuid not null references public.vehicles (id),
  customer_id uuid not null references public.customers (id),
  reservation_id uuid references public.reservations (id),
  inquiry_id uuid references public.inquiries (id),
  staff_id uuid references public.profiles (id),
  incoterm text not null default 'FOB' check (incoterm in ('FOB', 'CFR', 'CIF')),
  price_usd numeric(12, 2) not null check (price_usd > 0),
  freight_usd numeric(12, 2) not null default 0 check (freight_usd >= 0),
  insurance_usd numeric(12, 2) not null default 0 check (insurance_usd >= 0),
  other_charges_usd numeric(12, 2) not null default 0 check (other_charges_usd >= 0),
  total_usd numeric(12, 2) generated always as (price_usd + freight_usd + insurance_usd + other_charges_usd) stored,
  status text not null default 'awaiting_payment'
    check (status in ('awaiting_payment', 'partially_paid', 'paid', 'shipping', 'delivered', 'completed', 'cancelled')),
  invoice_no text unique,
  notes text check (char_length(notes) <= 2000),
  sold_at timestamptz not null default now(),
  completed_at timestamptz,
  cancelled_at timestamptz,
  cancel_reason text check (char_length(cancel_reason) <= 500),
  is_demo boolean not null default false,
  created_by uuid references public.profiles (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- A vehicle can only be sold once (unless the sale is cancelled).
create unique index sales_one_per_vehicle
  on public.sales (vehicle_id) where status <> 'cancelled';
create index sales_customer_idx on public.sales (customer_id);

create table public.payments (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.sales (id),
  customer_id uuid not null references public.customers (id),
  amount_usd numeric(12, 2) not null check (amount_usd > 0),
  method text not null default 'bank_transfer' check (method in ('bank_transfer', 'card', 'cash', 'other')),
  reference text check (char_length(reference) <= 120),
  paid_on date not null default current_date,
  -- recorded (by sales) -> verified (by admin) | void (by admin). Never deleted.
  status text not null default 'recorded' check (status in ('recorded', 'verified', 'void')),
  note text check (char_length(note) <= 1000),
  recorded_by uuid references public.profiles (id),
  verified_by uuid references public.profiles (id),
  verified_at timestamptz,
  void_reason text check (char_length(void_reason) <= 500),
  is_demo boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index payments_sale_idx on public.payments (sale_id);

create table public.shipments (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null unique references public.sales (id),
  customer_id uuid not null references public.customers (id),
  status text not null default 'awaiting_booking'
