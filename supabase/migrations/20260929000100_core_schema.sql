  vessel_name text check (char_length(vessel_name) <= 120),
  voyage_no text check (char_length(voyage_no) <= 40),
  port_of_loading text check (char_length(port_of_loading) <= 120),
  port_of_discharge text check (char_length(port_of_discharge) <= 120),
  etd date,
