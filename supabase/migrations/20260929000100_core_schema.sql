  internal_cost_jpy numeric(14, 0) check (internal_cost_jpy >= 0),
  internal_cost_usd numeric(12, 2) check (internal_cost_usd >= 0),
  supplier text check (char_length(supplier) <= 160),
  auction_house text check (char_length(auction_house) <= 160),
  purchase_date date,
  internal_notes text check (char_length(internal_notes) <= 5000),
  updated_by uuid references public.profiles (id),
  updated_at timestamptz not null default now()
);

create table public.vehicle_translations (
  vehicle_id uuid not null references public.vehicles (id) on delete cascade,
  locale text not null check (locale in ('en', 'ja', 'ar')),
  title text check (char_length(title) <= 200),
  description text check (char_length(description) <= 10000),
  remarks text check (char_length(remarks) <= 4000),
  updated_at timestamptz not null default now(),
  primary key (vehicle_id, locale)
);

create table public.vehicle_features (
  vehicle_id uuid not null references public.vehicles (id) on delete cascade,
  feature_code text not null references public.features (code) on delete cascade,
  primary key (vehicle_id, feature_code)
);

create table public.vehicle_media (
  id uuid primary key default gen_random_uuid(),
  vehicle_id uuid not null references public.vehicles (id) on delete cascade,
  kind text not null default 'photo'
    check (kind in ('photo', 'inspection_sheet', 'auction_sheet', 'view360', 'video', 'other')),
  -- Public media live in the public `vehicle-photos` bucket; private media in
  -- the staff-only `vehicle-internal` bucket.
  bucket text not null default 'vehicle-photos' check (bucket in ('vehicle-photos', 'vehicle-internal')),
  storage_path text not null check (char_length(storage_path) <= 500),
  is_public boolean not null default true,
  sort_order smallint not null default 0,
  caption text check (char_length(caption) <= 200),
  mime_type text,
  size_bytes integer check (size_bytes between 0 and 10485760),
  created_by uuid references public.profiles (id),
  created_at timestamptz not null default now(),
  unique (bucket, storage_path),
  constraint vehicle_media_bucket_matches_visibility
    check ((is_public and bucket = 'vehicle-photos') or (not is_public and bucket = 'vehicle-internal'))
);

create index vehicle_media_vehicle_idx on public.vehicle_media (vehicle_id, sort_order);

create table public.vehicle_price_history (
